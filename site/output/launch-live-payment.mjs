 const layout=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,frames:[...document.querySelectorAll('iframe')].map(f=>({height:f.getBoundingClientRect().height,width:f.getBoundingClientRect().width}))}));
 assert.ok(layout.scrollWidth<=layout.width,'Payment does not overflow on mobile');
 assert.equal(await pay.isVisible(),true,'Mobile Pay control is reachable');
