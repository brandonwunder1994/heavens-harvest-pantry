 const payment=page.frameLocator('iframe[name="embedded-checkout"]');
 await payment.getByText('$10.16',{exact:true}).first().waitFor({timeout:60000});
 await payment.getByRole('textbox',{name:/email/i}).waitFor({timeout:60000});
 const pay=payment.getByTestId('hosted-payment-submit-button');
 await pay.waitFor({timeout:60000});
 await payment.getByRole('textbox',{name:/email/i}).scrollIntoViewIfNeeded();
